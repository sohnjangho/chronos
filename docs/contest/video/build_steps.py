def main():
    B.WORK.mkdir(parents=True, exist_ok=True)
    only = sys.argv[sys.argv.index('--only') + 1].split(',') if '--only' in sys.argv else None
    todo = [s for s in S if not only or s['id'] in only]
    with ThreadPoolExecutor(6) as ex:  # 내레이션을 먼저 한꺼번에 받아 둔다(캐시)
        list(ex.map(lambda s: B.scene_tts(s['lines']), todo))
    durs = {}
    for seg in S:
        p = B.WORK / f"{seg['id']}.mp4"
        if seg in todo:
            durs[seg['id']] = B.build(seg)
        else:
            durs[seg['id']] = float(subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', p], capture_output=True, text=True).stdout)
    lst = B.WORK / 'list.txt'
    lst.write_text(''.join(f"file '{B.WORK / (s['id'] + '.mp4')}'\n" for s in S))
    raw = B.WORK / 'joined.mp4'
    B.ff('-f', 'concat', '-safe', '0', '-i', lst, '-c', 'copy', raw)
    final = B.OUT / 'ChronOS_시연영상_단계별.mp4'
    B.ff('-i', raw, '-c:v', 'copy', '-af', B.AFX, '-c:a', 'aac', '-b:a', '192k', '-ar', '48000', final)
    tot = sum(durs.values())
    print(json.dumps({k: round(v, 1) for k, v in durs.items()}, ensure_ascii=False))
    print(f'합계 {tot:.1f}s ({int(tot // 60)}:{int(tot % 60):02d}) → {final}')


if __name__ == '__main__':
    main()
